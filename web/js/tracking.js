const esc = (v) =>
    String(v ?? "").replace(/[&<>"']/g, (c) => ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
    })[c]);

const time = (v) => {
    const s = Math.max(0, Number(v) || 0);
    const m = Math.floor(s / 60);
    return `${String(m).padStart(2, "0")}:${(s % 60).toFixed(2).padStart(5, "0")}`;
};

function objectTable(rows, unique) {
    if (!rows?.length) {
        return `<p class="empty-note">No object records available.</p>`;
    }

    const columns = unique
        ? [
            ["object_id", "Object"],
            ["class_name", "Class"],
            ["first_sec", "First seen"],
            ["last_sec", "Last seen"],
            ["duration_sec", "Duration"],
            ["fragments", "Fragments"],
            ["detections", "Detections"],
            ["distance_px", "Distance"],
            ["avg_speed_px_s", "Average speed"],
        ]
        : [
            ["track_id", "Track ID"],
            ["class_name", "Class"],
            ["first_sec", "First seen"],
            ["last_sec", "Last seen"],
            ["duration_sec", "Duration"],
            ["detections", "Detections"],
            ["distance_px", "Distance"],
            ["avg_speed_px_s", "Average speed"],
        ];

    return `
    <div class="table-scroll">
      <table class="data-table">
        <thead>
          <tr>${columns.map(([, label]) => `<th>${label}</th>`).join("")}</tr>
        </thead>
        <tbody>
          ${rows.slice(0, 100).map((row) => `
            <tr>
              ${columns.map(([key]) => {
        let value = row[key];

        if (key === "first_sec" || key === "last_sec") {
            value = time(value);
        } else if (
            ["duration_sec", "distance_px", "avg_speed_px_s"].includes(key)
        ) {
            value = Number(value || 0).toFixed(1);
        }

        return `<td>${esc(value)}</td>`;
    }).join("")}
            </tr>
          `).join("")}
        </tbody>
      </table>
    </div>
    ${rows.length > 100
            ? `<p class="muted-copy">Showing the first 100 of ${rows.length} records.</p>`
            : ""}
  `;
}

export default async function mount(VA) {
    const { body } = VA.section("tracking");

    const [rawTracks, uniqueObjects] = await Promise.all([
        VA.state.tsum || [],
        VA.state.uniq || [],
    ]);

    const classCounts = {};

    for (const row of rawTracks) {
        const name = row.class_name || "unknown";
        classCounts[name] = (classCounts[name] || 0) + 1;
    }

    const totalRaw = rawTracks.length;
    const totalUnique = uniqueObjects.length;

    body.innerHTML = `
    <div class="metrics">
      <div class="metric">
        <div class="n">${totalRaw}</div>
        <div class="l">Raw track IDs</div>
        <div class="s">Tracks retained by the tracker</div>
      </div>
      <div class="metric">
        <div class="n">${totalUnique}</div>
        <div class="l">Unique objects</div>
        <div class="s">After fragmented-track merging</div>
      </div>
      <div class="metric">
        <div class="n">${Object.keys(classCounts).length}</div>
        <div class="l">Object classes</div>
        <div class="s">Classes represented in raw tracks</div>
      </div>
    </div>

    <div class="analysis-grid">
      <article class="analysis-card">
        <div class="card-heading">
          <h3>Object trajectories</h3>
        </div>
        <img
          class="analysis-image"
          src="${VA.base}/tracking/trajectories.png"
          alt="Object trajectories"
          loading="lazy"
        >
      </article>

      <article class="analysis-card">
        <div class="card-heading">
          <h3>Path heatmap</h3>
        </div>
        <img
          class="analysis-image"
          src="${VA.base}/tracking/path_heatmap.png"
          alt="Object path heatmap"
          loading="lazy"
        >
      </article>
    </div>

    <article class="analysis-card">
      <div class="card-heading">
        <h3>Object counts over time</h3>
      </div>
      <img
        class="analysis-image"
        src="${VA.base}/tracking/object_counts.png"
        alt="Object counts over time"
        loading="lazy"
      >
    </article>

    <article class="analysis-card table-card">
      <div class="card-heading">
        <h3>Unique objects</h3>
        <span class="mono">${totalUnique} records</span>
      </div>
      ${objectTable(uniqueObjects, true)}
    </article>

    <article class="analysis-card table-card">
      <div class="card-heading">
        <h3>Raw track summary</h3>
        <span class="mono">${totalRaw} track IDs</span>
      </div>
      ${objectTable(rawTracks, false)}
    </article>

    <p class="muted-copy">
      Track IDs are generated by the tracker. The unique-object table represents
      the output of the track-merging cleanup stage; it should not be interpreted
      as a guaranteed count of distinct real-world individuals.
    </p>
  `;
}